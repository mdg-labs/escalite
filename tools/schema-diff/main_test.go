func TestValidMigrationName(t *testing.T) {
	tests := []struct {
		name  string
		valid bool
	}{
		{name: "bootstrap", valid: true},
		{name: "add_foo_column", valid: true},
		{name: "add_column_v2", valid: true},
		{name: "", valid: false},
		{name: "1starts_with_digit", valid: false},
		{name: "has-dash", valid: false},
		{name: "has space", valid: false},
	}

	for _, tc := range tests {
		if got := validMigrationName(tc.name); got != tc.valid {
			t.Fatalf("validMigrationName(%q) = %v, want %v", tc.name, got, tc.valid)
		}
	}
}

func TestFormatGooseMigration(t *testing.T) {
	out := formatGooseMigration("ALTER TABLE foo ADD COLUMN bar text;")
	if !strings.HasPrefix(out, "-- Code generated by tools/schema-diff; DO NOT EDIT.\n-- +goose Up\n") {
		t.Fatalf("missing goose Up header: %q", out)
	}
	if !strings.Contains(out, "ALTER TABLE foo ADD COLUMN bar text;") {
		t.Fatalf("missing plan SQL: %q", out)
	}
	if !strings.Contains(out, "-- +goose Down\n-- generated migration; manual rollback required") {
		t.Fatalf("missing goose Down footer: %q", out)
	}
}
